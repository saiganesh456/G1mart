function getPackshotImage(name: string, brand?: string, fallbackImg?: string): string {
  const query = `${name} ${brand || ''}`;
  for (const [regex, packshotPath] of PACKSHOT_MAP) {
    if (regex.test(query)) {
      return packshotPath;
    }
  }
  return fallbackImg || '/products/placeholder.svg';
}

